// Lead-magnet registry.
// Each entry powers a gate page at /downloads/<slug> AND can be referenced as
// the magnet slug by /api/leads/magnet.
//
// Fields:
//   slug      — URL slug for the gate page and the lead document
//   title     — H1 on the gate page and form heading
//   subtitle  — One-sentence description
//   file      — Public path to the hosted PDF (e.g. /downloads/foo.pdf).
//               null = lead-capture-only flows.
//   cta       — Button label on the form
//   topicLabel— Label shown above the dropdown on the form (if used)
//
// COMMUNITY GUIDES (community-guide-<slug>) are generated by two scripts:
//   scripts/build-community-guides.js               — 12 featured (hand-curated)
//   scripts/build-supplementary-community-guides.js — 34 remaining (data-driven)
//
// They are used by the /community-quiz funnel AND by the inline magnet on
// each /communities/<slug> detail page. The COMMUNITIES table in lib/data.js
// is the single source of truth; this file mirrors every entry programmatically
// so the two never drift.

import { COMMUNITIES } from './data';

const communityGuides = Object.fromEntries(
  COMMUNITIES.map(c => [
    `community-guide-${c.slug}`,
    {
      slug: `community-guide-${c.slug}`,
      title: `${c.name}: Community Guide`,
      subtitle: `A practical walkthrough of ${c.name}: the course, the club model, the real-estate footprint, and who the community honestly fits.`,
      file: `/downloads/community-guide-${c.slug}.pdf`,
      cta: 'Get the guide',
      topicLabel: 'How are you considering Scottsdale?',
      requirePhone: true
    }
  ])
);

export const leadMagnets = {
  'scottsdale-buyers-guide-2026': {
    slug: 'scottsdale-buyers-guide-2026',
    title: 'The 2026 Scottsdale Golf Buyer’s Guide',
    subtitle: 'An editorial guide to luxury golf real estate in Scottsdale, Arizona: communities, clubs, market positioning, and what each buyer profile should actually consider.',
    file: '/downloads/scottsdale-buyers-guide-2026.pdf',
    cta: 'Download the guide',
    topicLabel: 'Which best describes you?',
    requirePhone: true
  },
  ...communityGuides
};

export function getMagnet(slug) {
  return leadMagnets[slug] || null;
}

export function listMagnets() {
  return Object.values(leadMagnets);
}

